def gen_methods_overview() -> str:
    """The Methods section landing (docs/methodology/methods/index.md): PUBLISHED_METHODS as
    scannable cards, then the same set as a table. Both are emitted deliberately -- the cards
    are for choosing which method to read, the table is for comparing status and one-line ideas
    at a glance without scanning a grid. Prose (title, one-line idea, badge) is registry-driven;
    no run data."""
    parts = ["# The methods\n"]
    parts.append("Every method proposes a different road network for the same blocks; all are "
                 "graded on the same basis — permeability (the benefit) against displacement (the "
                 "cost). Each page shows the method's roads on the ground and its numbers from the "
                 "actual runs.\n")
    # That basis, as one figure, before the reader picks a method to read about: the interactive
    # frontier (falling back to its own static PNG). Placed here with no heading of its own on
    # purpose -- it illustrates the sentence directly above it, and a heading between that sentence
    # and the cards would leave the cards sitting under the wrong one.
    parts.append(_frontier_figure())

    cards = []
    for m in PUBLISHED_METHODS:
        label = m.status or m.badge
        cls = "pill-progress" if m.status else "pill-done"
        # Uppercase only the first letter -- str.capitalize() would lowercase the rest and turn
        # "Manhattan-style" into "manhattan-style", "OSM" into "osm".
        idea = m.idea[:1].upper() + m.idea[1:]
        cards.append(f"-   **[{m.display_title}]({m.slug}.md)**\n\n"
                     f"    {idea}.\n\n"
                     f'    <span class="pill {cls}">{label}</span>')
    parts.append('<div class="grid cards" markdown>\n\n' + "\n\n".join(cards) + "\n\n</div>\n")

    parts.append("## At a glance\n")
    rows = []
    for m in PUBLISHED_METHODS:
        label = m.status or m.badge
        cls = "pill-progress" if m.status else "pill-done"
        rows.append([f"[{m.display_title}]({m.slug}.md)", m.idea,
                     f'<span class="pill {cls}">{label}</span>'])
    parts.append(_table(["Method", "Idea", "Status"], rows))
    return "\n".join(parts)


