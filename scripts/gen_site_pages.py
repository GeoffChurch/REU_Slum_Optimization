PARTIALS = DOCS / "_partials"


_LEADING_COMMENT = re.compile(r"\A\s*<!--.*?-->\s*", flags=re.S)


def _render_partial(name: str) -> str:
    """Read docs/_partials/<name>.md, strip its LEADING maintainer comment, and fill every known
    marker. Every partial opens with an internal note (do-not-edit pointer, marker inventory,
    sometimes ruling numbers or plan paths) that has no business in a public site's page source --
    HTML comments pass through python-markdown untouched into the built HTML. Only the leading
    comment is stripped: a partial may legitimately carry one later in its body (e.g.
    permeability.md's figure placeholder), and those must survive. Unknown markers are left alone
    so the closed-set test can catch them; a missing partial is an error, not an empty page."""
    text = (PARTIALS / f"{name}.md").read_text(encoding="utf-8")
    text = _LEADING_COMMENT.sub("", text, count=1).rstrip()
    for marker, produce in MARKERS.items():
        text = text.replace(f"<!-- {marker} -->", produce())
    return text


def _write_page(path: Path, body: str, *, depth: int, url_depth: int,
                title: str | None = None) -> None:
    """Write one generated page, fixing asset paths for BOTH link forms, which MkDocs treats
    differently:

    `depth` -- Markdown links `](assets/...)`. MkDocs resolves these against the SOURCE file, so a
    page nested `depth` levels below docs/ needs ../ per level; MkDocs then rewrites the output
    URL itself.

    `url_depth` -- raw HTML `src="assets/..."`, `href="assets/..."` and `data-bundle="assets/..."`
    (the widget mount point's fetch URL -- same rule, it is raw HTML too) inside the <figure>
    blocks. MkDocs does NOT touch raw HTML, so these must already be correct against the page's
    SERVED url. With use_directory_urls, results/frontier.md is served at
    <base>/results/frontier/ and methodology/methods/peel.md at
    <base>/methodology/methods/peel/, so the served depth is not the same as the source depth --
    results/frontier.md is depth 1 but url_depth 2. Getting this wrong 404s every figure -- or,
    for data-bundle, silently fails the widget's fetch -- on that page."""
    # YAML front matter, when given, sets the page's nav label. Without it MkDocs derives the
    # label from the FILENAME -- "clearance_looped" became "Clearance looped" in the sidebar, not
    # "Looped Tree" -- because it does not read the H1 for nav purposes. Emitting the title here
    # keeps method_labels.py the single source of the display name for the heading AND the nav,
    # instead of a hand-written copy in mkdocs.yml that silently goes stale.
    front = f'---\ntitle: "{title}"\n---\n' if title else ""
    text = front + GENERATED_NOTE + body.rstrip() + "\n"
    if depth:
        text = text.replace("](assets/", "](" + "../" * depth + "assets/")
    if url_depth:
        up = "../" * url_depth
        text = text.replace('src="assets/', f'src="{up}assets/')
        text = text.replace('href="assets/', f'href="{up}assets/')
        text = text.replace('data-bundle="assets/', f'data-bundle="{up}assets/')
    path.write_text(text, encoding="utf-8")


def _assert_widget_bundle_present(pages_with_widgets: bool) -> None:
    """A site built without `pixi run web` emits a <script> tag for a file that is not there: every
    widget silently fails to boot, the PNG fallbacks still render, and the page looks FINE. Turn
    that into a build failure. File existence needs no imports, so this respects the stdlib-only
    contract."""
    if pages_with_widgets and not (DOCS / "js" / "widgets.js").exists():
        raise SystemExit(
            "docs/js/widgets.js is missing but a page carries a widget mount point -- run "
            "`pixi run web` (CI does this in deploy-site.yml before mkdocs build)")


def main() -> None:
    # Generated (gitignored) pages only. The handwritten committed pages (background.md,
    # team.md) are never touched.
    (DOCS / "index.md").write_text(GENERATED_NOTE + _render_partial("intro") + "\n",
                                   encoding="utf-8")

    # reproduce.md serves at <base>/reproduce/ -- source depth 0, url_depth 1. Written directly
    # into docs/, not into a cleared subdirectory, so (unlike results/ and methodology/ below) it
    # is not subject to the rmtree/mkdir hazard those blocks document (ruling F4).
    _write_page(DOCS / "reproduce.md", _render_partial("reproduce"), depth=0, url_depth=1,
                title="Reproduce")

    results_dir = DOCS / "results"
    if results_dir.exists():
        shutil.rmtree(results_dir)
    results_dir.mkdir(parents=True, exist_ok=True)
    # results/frontier.md serves at <base>/results/frontier/ -- source depth 1, url_depth 2.
    _write_page(results_dir / "frontier.md", gen_benchmark_section(), depth=1, url_depth=2,
                title="Frontier benchmark")
    # results/bakeoff.md serves at <base>/results/bakeoff/ -- same depth/url_depth as frontier.md
    # above, and MUST follow the results_dir rmtree/mkdir block above it (ruling F4): an insertion
    # above that block would delete this page as soon as it was written.
    _write_page(results_dir / "bakeoff.md", _render_partial("bakeoff"), depth=1, url_depth=2,
                title="Screen bake-off")
    # results/nairobi.md serves at <base>/results/nairobi/ -- same depth/url_depth as its two
    # siblings above, and (ruling F4) MUST likewise follow the results_dir rmtree/mkdir block.
    _write_page(results_dir / "nairobi.md", _render_partial("nairobi"), depth=1, url_depth=2,
                title="Second city: Nairobi")

    # docs/methodology/ -- rebuilt from scratch each run. Every _write_page into this directory,
    # including the methodology/methods/ pages below, MUST come after this rmtree/mkdir, or it
    # deletes the page just written -- same reason permeability.md and displacement.md have to.
    methodology_dir = DOCS / "methodology"
    if methodology_dir.exists():
        shutil.rmtree(methodology_dir)
    methodology_dir.mkdir(parents=True, exist_ok=True)
    _write_page(methodology_dir / "index.md", _render_partial("methodology"),
                depth=1, url_depth=1, title="Methodology")
    _write_page(methodology_dir / "screening.md", _render_partial("screening"),
                depth=1, url_depth=2, title="Screening")
    _write_page(methodology_dir / "permeability.md", _render_partial("permeability"),
                depth=1, url_depth=2, title="Permeability")
    _write_page(methodology_dir / "displacement.md", _render_partial("displacement"),
                depth=1, url_depth=2, title="Displacement")

    methods_dir = methodology_dir / "methods"
    methods_dir.mkdir(parents=True, exist_ok=True)
    # methodology/methods/index.md serves at <base>/methodology/methods/ (2 segments);
    # methodology/methods/peel.md at <base>/methodology/methods/peel/ (3). Source depth is 2 for
    # both. Getting url_depth wrong 404s every figure on the page.
    _write_page(methods_dir / "index.md", gen_methods_overview(), depth=2, url_depth=2,
                title="The methods")
    for m in METHODS:
        _write_page(methods_dir / f"{m.slug}.md", gen_method_section(m), depth=2, url_depth=3,
                    title=m.display_title)

    # Scoped to exactly the GENERATED (gitignored) page set -- docs/index.md, docs/reproduce.md,
    # docs/methodology/**, docs/results/** -- never docs/superpowers/ or docs/_partials/. Both of
    # those are committed prose that can legitimately quote 'data-widget="perm-graph"' (this
    # file's own design spec does, as an example snippet) without a single generated page
    # actually carrying a mount point; scanning them would make the guard fire on a site that
    # built perfectly fine.
    generated_pages = ([DOCS / "index.md", DOCS / "reproduce.md"]
                       + sorted(methodology_dir.rglob("*.md"))
                       + sorted(results_dir.rglob("*.md")))
    pages_with_widgets = any('data-widget="' in p.read_text(encoding="utf-8")
                             for p in generated_pages if p.exists())
    _assert_widget_bundle_present(pages_with_widgets)

    print("wrote docs/index.md, docs/reproduce.md, docs/results/frontier.md, "
          "docs/methodology/*.md, docs/methodology/methods/*.md")


if __name__ == "__main__":
    main()
