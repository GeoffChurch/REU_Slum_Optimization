def main() -> None:
    # leftovers from the earlier multi-page layout (both generated, both gitignored)
    if (DOCS / "methods").exists():
        shutil.rmtree(DOCS / "methods")
    (DOCS / "benchmark.md").unlink(missing_ok=True)

    intro_path = DOCS / "_intro.md"
    intro = intro_path.read_text() if intro_path.exists() else "# reblock\n"
    parts = [GENERATED_NOTE, intro.rstrip() + "\n"]
    parts += [gen_method_section(m) for m in METHODS]
    parts.append(gen_benchmark_section())
