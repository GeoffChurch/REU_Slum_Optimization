def _render_partial(name: str) -> str:
    """Read docs/_partials/<name>.md and fill every known marker. Unknown markers are left alone so
    the closed-set test can catch them; a missing partial is an error, not an empty page."""
    text = (PARTIALS / f"{name}.md").read_text(encoding="utf-8").rstrip()
    for marker, produce in MARKERS.items():
        text = text.replace(f"<!-- {marker} -->", produce())
    return text


def _write_page(path: Path, body: str, *, depth: int, url_depth: int,
                title: str | None = None) -> None:
    """Write one generated page, fixing asset paths for BOTH link forms, which MkDocs treats
    differently:

    `depth` -- Markdown links `](assets/...)`. MkDocs resolves these against the SOURCE file, so a
    page nested `depth` levels below docs/ needs ../ per level; MkDocs then rewrites the output
    URL itself.

    `url_depth` -- raw HTML `src="assets/..."` inside the <figure> blocks. MkDocs does NOT touch
    raw HTML, so these must already be correct against the page's SERVED url. With
    use_directory_urls, results/frontier.md is served at <base>/results/frontier/ and
    methodology/methods/peel.md at <base>/methodology/methods/peel/, so the served depth is not
    the same as the source depth -- results/frontier.md is depth 1 but url_depth 2. Getting this
    wrong 404s every figure on that page."""
    # YAML front matter, when given, sets the page's nav label. Without it MkDocs derives the
    # label from the FILENAME -- "clearance_looped" became "Clearance looped" in the sidebar, not
    # "Looped Tree" -- because it does not read the H1 for nav purposes. Emitting the title here
    # keeps method_labels.py the single source of the display name for the heading AND the nav,
    # instead of a hand-written copy in mkdocs.yml that silently goes stale.
    front = f'---\ntitle: "{title}"\n---\n' if title else ""
    text = front + GENERATED_NOTE + body.rstrip() + "\n"
    if depth:
        text = text.replace("](assets/", "](" + "../" * depth + "assets/")
    if url_depth:
        up = "../" * url_depth
        text = text.replace('src="assets/', f'src="{up}assets/')
        text = text.replace('href="assets/', f'href="{up}assets/')
    path.write_text(text, encoding="utf-8")


