def _k_section(m: M) -> list[str]:
    parts: list[str] = []
    if not m.outputs_frag:
        return parts
    headers, rows, dirs = _k_runs(m.outputs_frag, m.outputs_flags)
    if not rows:
        return parts
    parts.append("### Single-block k-complexity runs\n")
    parts.append("Access depth is peel-k: the number of BFS rings between the deepest parcel and "
                 "a street (`k after = 1` means every parcel fronts a road). `road components` "
                 "counts disconnected pieces in the proposed network — 1 is a single buildable "
                 "network. Read from the `outputs/*/run.log` evaluation logs on disk:\n")
    parts.append(_table(headers, rows))
    pair = _k_render_pair(dirs, "runs")
    if pair:
        parts.append("\n" + _img_row([("before", pair[0]), ("after", pair[1])]))
    return parts


def gen_method_section(m: M) -> str:
    parts = [f"## {m.title}\n"]
    if m.status:
        parts.append(f"**Status: {m.status}.**\n")
    if m.blurb:
        parts.append(m.blurb + "\n")
    if m.conf and (ROOT / "conf" / "method" / f"{m.conf}.yaml").exists():
        parts.append(f"Configuration: [`conf/method/{m.conf}.yaml`](https://github.com/"
                     f"jmendoza167/REU_Slum_Optimization/blob/main/conf/method/{m.conf}.yaml)\n")
    if m.slug == "dream_come_true":
        parts.append(DREAM_BODY)
    body = (_mc_section(m) if m.mc_key else []) + \
           (_mb_section(m) if m.mb_key else []) + _k_section(m)
    parts += body
    if m.slug == "peel" and not body:
        parts.append("*No evaluation artifacts for this method were found on disk.*\n")
    return "\n".join(parts)


