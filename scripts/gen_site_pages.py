def _frontier_terminal(rows: list[dict[str, str]], method: str) -> tuple[float, float] | None:
    """(terminal displacement, terminal permeability) for one method in a permeability frontier
    CSV -- the full-build-out point, i.e. the sampled prefix with the most road (== most
    displacement, since both axes are fractions in [0, 1) that only grow as road is added)."""
    pts = [(float(r["displacement"]), float(r["permeability"])) for r in rows
           if r["method"] == method]
    return max(pts) if pts else None


def _mc_summary(method: str) -> dict[str, str] | None:
    """Terminal-point (full build-out) summary for the single-block head-to-head, from the
    permeability frontier CSV: the displacement spent and the permeability reached at full build."""
    term = _frontier_terminal(_read_csv(MC / "frontier_permeability.csv"), method)
    if term is None:
        return None
    disp, perm = term
    return {"homes displaced": _pct(disp), "permeability": _pct(perm)}


def _mb_lens_rows(method: str) -> tuple[dict[str, str] | None, dict[str, str] | None]:
    """This method's row from the two permeability lenses: matched-displacement (equal home-cost,
    compare the permeability each buys) and matched-permeability (equal outcome, compare the homes
    each spends)."""
    disp = next((r for r in _read_csv(MB / "lens_displacement.csv") if r["method"] == method), None)
    perm = next((r for r in _read_csv(MB / "lens_permeability.csv") if r["method"] == method), None)
    return disp, perm


def _dict_table(row: dict[str, str]) -> str:
    head = "| " + " | ".join(row) + " |"
    sep = "|" + "|".join(["---"] * len(row)) + "|"
    return f"{head}\n{sep}\n| " + " | ".join(row.values()) + " |\n"


def _table(headers: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join(["---"] * len(headers)) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out) + "\n"


def _screen_table() -> str:
    """The screen bake-off ranking, read straight from screen_comparison.csv's own columns --
    including `floor`, which already carries each metric's shipped absolute gate (empty for the
    two metrics never shipped as a gate). Deliberately NOT re-derived from conf/metric/*.yaml: a
    metric's CSV label (e.g. "depth_density proxy   √(nA)/P · n/A") does not round-trip to its
    config stem by splitting on whitespace -- `.split()[0]` lands on `depth_density`, which names
    a DIFFERENT, percentile-gated metric than `depth_density_proxy`. The CSV's own floor column
    has no such ambiguity. Empty string when the artifact is absent, per the dir-reader contract:
    a section is emitted only when its data exists."""
    rows = _read_csv(BAKEOFF / "screen_comparison.csv")
    if not rows:
        return ""
    body = [["metric", "AUC", "precision in top 1%", "shipped floor"]]
    for r in rows:
        body.append([r["metric"], _num(float(r["auc"]), 3), _pct(float(r["prec@1%"])),
                     r["floor"] or "—"])
    return _table(body[0], body[1:])


def _bakeoff_floors_table() -> str:
    """Both shipped screens at their absolute floors: pool size, precision, recall. Empty when
    the artifact is absent, per the dir-reader contract."""
    rows = [r for r in _read_csv(BAKEOFF / "screen_comparison.csv") if r.get("floor")]
    if not rows:
        return ""
    body = [[r["metric"], _num(float(r["floor_n"])), _pct(float(r["floor_prec"])),
             _pct(float(r["floor_recall"]))] for r in rows]
    return _table(["screen at its floor", "blocks", "precision", "recall"], body)


def _bakeoff_figures() -> str:
    """The three committed bake-off figures, in narrative order. Each is emitted only if present,
    per the dir-reader contract."""
    wanted = [("precision_recall.png", "Precision and recall across the candidate screens."),
              ("city_map.png", "Where the shipped screen and its predecessor disagree, city-wide."),
              ("settlements.png",
               "The four settlements of sharpest disagreement. Green sits inside the gold "
               "settlement outlines; red sits outside them.")]
    out: list[str] = []
    for name, caption in wanted:
        url = _copy_asset(BAKEOFF / name, "bakeoff")
        if url:
            out.append(_figure(url, caption, caption))
    return "\n\n".join(out)


def _bakeoff_scale() -> str:
    """Survey scale, read from the ground-truth artifact rather than typed into prose -- and a
    COMPLETE SENTENCE, never a noun phrase (ruling F5). The generator's dir-reader contract lets
    ground_truth.json be absent on a partial checkout, in which case this returns "" -- a noun
    phrase spliced mid-sentence would then leave a dangling fragment ("The survey covers ."); a
    whole sentence simply disappears instead, and docs/_partials/bakeoff.md places it as its own
    paragraph so the section around it reads correctly either way."""
    path = BAKEOFF / "ground_truth.json"
    if not path.exists():
        return ""
    g = json.loads(path.read_text(encoding="utf-8"))
    return (f"That survey contains {_num(g['structures'])} dwelling polygons, which cluster into "
            f"{_num(g['settlements'])} settlements and mark {_num(g['informal_blocks'])} of "
            f"{_num(g['total_blocks'])} Cape Town blocks informal.")


def _nairobi_table() -> str:
    """One row per Nairobi variant, read from its own artifacts. Absent variants simply do not
    appear -- a partial checkout yields a shorter table, never a placeholder row (same dir-reader
    contract as _k_runs, guarded on NAIROBI.exists() for the same reason that one guards on
    OUTPUTS.exists() before iterating).

    Ruling F6: a field missing from one variant's meta.json renders as an em dash for THAT row,
    never a fabricated number. This mirrors the guarded `meta.get(...)` pattern _key_figures()
    already uses -- not the brief's original `_num(meta.get("region_members", 0))`, which would
    publish a confident 0 for a field that was simply never written."""
    rows: list[list[str]] = []
    if not NAIROBI.exists():
        return ""
    for d in sorted(p for p in NAIROBI.iterdir() if p.is_dir()):
        meta_path = d / "meta.json"
        if not meta_path.exists():
            continue
        meta = json.loads(meta_path.read_text(encoding="utf-8"))
        methods = {r["method"] for r in _read_csv(d / "lens_permeability.csv")}
        rows.append([f"[{d.name}](https://github.com/jmendoza167/REU_Slum_Optimization/"
                     f"tree/main/examples/nairobi/{d.name})",
                     f"`{meta['metric']}`" if meta.get("metric") else "—",
                     _num(meta["region_members"]) if meta.get("region_members") else "—",
                     "yes" if "osm_footpaths" in methods else "—"])
    if not rows:
        return ""
    return _table(["variant", "metric", "blocks in region", "OSM baseline"], rows)


# ---------------------------------------------------------------- outputs/ scanning (k-complexity)

def _run_method_target(run_dir: Path) -> str | None:
    cfg = run_dir / ".hydra" / "config.yaml"
    if not cfg.exists():
        return None
    m = re.search(r"_target_:\s*(reblock\.methods\.[\w.]+)", cfg.read_text(encoding="utf-8"))
    return m.group(1) if m else None


def _run_flag(run_dir: Path, key: str) -> str | None:
    cfg = run_dir / ".hydra" / "config.yaml"
    if not cfg.exists():
        return None
    m = re.search(rf"^\s+{key}:\s*(\S+)\s*$", cfg.read_text(encoding="utf-8"), re.M)
    return m.group(1) if m else None


def _kcomplexity_lines(run_dir: Path) -> list[tuple[str, dict[str, float]]]:
    log = run_dir / "run.log"
    if not log.exists():
        return []
    out = []
    for line in log.read_text(encoding="utf-8").splitlines():
        if "'kcomplexity'" not in line:
            continue
        m = re.search(r"INFO\] - (\S+) (\{.*\})\s*$", line)
        if m:
            out.append((m.group(1), ast.literal_eval(m.group(2))["kcomplexity"]))
    return out


def _k_runs(target_frag: str, flags: list[str]) -> tuple[list[str], list[list[str]], list[Path]]:
    """All committed-nothing single-block eval runs under outputs/ whose method matches.

    Returns (headers, rows, matching run dirs). Deduped on (block, metrics) so re-renders of the
    same run don't repeat.
    """
    headers = ["run", "block", "k before", "k after", "delta k", "added road (m)",
               "road components", *flags]
    rows: list[list[str]] = []
    dirs: list[Path] = []
    seen: set[tuple[str, float, float, float]] = set()
    if not OUTPUTS.exists():
        return headers, rows, dirs
    for d in sorted(p for p in OUTPUTS.iterdir() if p.is_dir()):
        target = _run_method_target(d)
        if target is None or target_frag not in target:
            continue
        lines = _kcomplexity_lines(d)
        if not lines:
            continue
        dirs.append(d)
        flag_vals = [_run_flag(d, f) or "—" for f in flags]
        for block, k in lines:
            key = (block, k["k_after"], k["added_road_length_m"], k["n_road_components"])
            if key in seen:
                continue
            seen.add(key)
            rows.append([f"`{d.name}`", f"`{block}`", _num(k["k_before"]), _num(k["k_after"]),
                         _num(k["delta_k"]), _num(k["added_road_length_m"]),
                         _num(k["n_road_components"]), *flag_vals])
    return headers, rows, dirs


def _k_render_pair(dirs: list[Path], sub: str) -> tuple[str, str] | None:
    """First before/after PNG render pair found among the matching run dirs."""
    for d in dirs:
        before = sorted(d.glob("*_before.png"))
        after = sorted(d.glob("*_after.png"))
        if before and after:
            b = _copy_asset(before[0], f"{sub}/{d.name}")
            a = _copy_asset(after[0], f"{sub}/{d.name}")
            if b and a:
                return b, a
    return None


