def _load_friendly_method_name() -> Callable[[str], str]:
    """Load the stdlib-only display-name map straight from its file, WITHOUT importing the reblock
    package: CI runs this script with only mkdocs-material installed (reblock is not importable),
    and method_labels.py has no third-party or intra-package imports, so executing it directly is
    safe and keeps this script's stdlib-only contract. This is the single source of method display
    names (Option A) -- shared with the frontier-plot legend and the generated example READMEs."""
    path = ROOT / "src" / "reblock" / "method_labels.py"
    spec = importlib.util.spec_from_file_location("reblock_method_labels", path)
    assert spec is not None and spec.loader is not None
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    name: Callable[[str], str] = mod.friendly_method_name
    return name


