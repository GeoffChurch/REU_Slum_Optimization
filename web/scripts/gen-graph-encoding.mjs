#!/usr/bin/env node
// Generates web/src/render/graph-encoding.generated.ts from examples/perm-graph/bundle.json's own
// `encoding` object -- the drawing vocabulary `render/canvas.ts`'s `draw` reads: the 256-stop
// potential ramp, the four layer colours, the edge line-width range, and the two mesh width norms.
//
// It exists because DrawRoad (web/src/widgets/draw-road.ts) SYNTHESISES the bundle it draws. Every
// other widget on this site is handed an `encoding` inside the bundle it fetches; DrawRoad's own
// bundle -- examples/authoring/block.json -- is the INPUT to a solve rather than a picture, and
// carries no encoding at all (web/src/authoring.d.ts). The three ways to get one were: fetch a
// second, 278 KB bundle at runtime for the ~3 KB of it that is the encoding; hand-copy 256 hex
// stops into TypeScript; or read them out of the committed artifact at build time, which is this.
//
// It is the SAME block. Checked directly, both artifacts on disk: `block_id` is
// ZAF.9.3.1_1_40972 in each, both carry 263 nodes and 745 edges, and their `rows`/`cols` arrays
// are equal element for element, with node positions agreeing to within the perm-graph bundle's
// own centimetre quantiser (max 0.005 m). So `width_norm` -- which is a property of THIS mesh's
// current and conductance distributions, not a style choice -- is the right scale for a road drawn
// on it, and the two figures a reader meets on the Permeability page draw one block in one
// palette at one width scale. `draw-road.ts` re-checks the `block_id` half of that at boot, since
// the two bundles are baked by two different scripts and could be re-baked apart.
//
// Same shape as gen-solve-source.mjs beside it, for the same reason: the generated file is NOT
// committed (.gitignore) and is regenerated by both `npm run build` and `npm run check` before
// either does anything else, so there is exactly one artifact that could go stale
// (examples/perm-graph/bundle.json itself), not two.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const bundlePath = fileURLToPath(new URL("../../examples/perm-graph/bundle.json", import.meta.url));
const outPath = fileURLToPath(new URL("../src/render/graph-encoding.generated.ts", import.meta.url));
const bundle = JSON.parse(readFileSync(bundlePath, "utf8"));

// No defaults on either read: the bundle is a genuinely open JSON boundary here (this script is
// plain JS with no type checker over it), so a re-bake that dropped either key must stop the build
// rather than emit a TypeScript file that compiles and draws nothing.
if (bundle.encoding === undefined) throw new Error(`${bundlePath} carries no "encoding"`);
if (bundle.block_id === undefined) throw new Error(`${bundlePath} carries no "block_id"`);

// `Encoding` is imported as a TYPE and the literal is annotated with it, so a field renamed in
// bundle.d.ts (which scripts/gen_web_bundle.py generates from the same bake) is a compile error
// here rather than a silently missing colour at draw time.
const contents =
  `// GENERATED by web/scripts/gen-graph-encoding.mjs from examples/perm-graph/bundle.json`
  + ` -- do not edit.\n`
  + `// Not committed (.gitignore): regenerated by \`npm run build\` and \`npm run check\`.\n`
  + `import type { Encoding } from "../bundle.js";\n`
  + `export const GRAPH_ENCODING: Encoding = ${JSON.stringify(bundle.encoding)};\n`
  + `/** The block examples/perm-graph/bundle.json was baked from, so a consumer can check that\n`
  + ` * the mesh-dependent half of GRAPH_ENCODING (\`width_norm\`) belongs to the block it is\n`
  + ` * drawing. */\n`
  + `export const GRAPH_ENCODING_BLOCK_ID = ${JSON.stringify(bundle.block_id)};\n`;

writeFileSync(outPath, contents);
